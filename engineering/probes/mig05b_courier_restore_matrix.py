"""MIG-05b: extend bounded compatibility matrix to authentic 97-event courier world.

Only disposable historical 41/56 fixtures generated by pinned runtime in CI.
Not a production save migration API. No source modification or silent version edit.
"""
from __future__ import annotations

from contextlib import closing
import hashlib
import inspect
import json
import os
from pathlib import Path
import shutil
import sqlite3
import tempfile

from carlos_sim import SQLiteEventStore, DomainEvent, TimeEngine
from carlos_sim.backup import BackupError, create_backup_bundle, restore_backup_bundle, verify_backup_bundle
from carlos_sim.domain import SCHEMA_VERSION, RULES_VERSION, canonical_hash
from carlos_sim.store import DuplicateCommand, UnsupportedVersion

SOURCE = Path("courier-original-41-56.sqlite").resolve()
WORLD = "play27-real-four-site-supply"
TARGET_SHA = "38ef0049478e4d62fd465dadc7c1eaf406b9b4d2"
assert (SCHEMA_VERSION, RULES_VERSION) == (42, 57)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def reject(error_types, action, description: str) -> None:
    try:
        action()
    except error_types:
        print("MIG05B_REJECTED " + description, flush=True)
        return
    raise AssertionError("unsafe success: " + description)


def read_historical(path: Path) -> tuple[list, list, dict]:
    """Strict immutable old history before building target."""
    with closing(sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)) as old:
        old.row_factory = sqlite3.Row
        old.execute("PRAGMA query_only=ON")
        assert old.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
        assert old.execute("PRAGMA foreign_key_check").fetchall() == []
        world = old.execute("SELECT * FROM worlds WHERE id=?", (WORLD,)).fetchone()
        assert world and (world["schema_version"], world["rules_version"]) == (41, 56)
        genesis = json.loads(world["initial_state"])
        assert canonical_hash(genesis) == world["initial_hash"]
        assert genesis["world_id"] == WORLD and genesis["revision"] == 0
        assert (genesis["schema_version"], genesis["rules_version"]) == (41, 56)
        events = list(old.execute(
            "SELECT * FROM events WHERE world_id=? ORDER BY seq", (WORLD,),
        ))
        commands = list(old.execute(
            "SELECT * FROM commands WHERE world_id=? ORDER BY first_revision", (WORLD,),
        ))
        assert len(events) == world["revision"] == 97
        assert len(commands) == 2
        assert [e["seq"] for e in events] == list(range(1, 98))
        for row in old.execute("SELECT revision,state,hash FROM snapshots WHERE world_id=?", (WORLD,)):
            state = json.loads(row["state"])
            assert canonical_hash(state) == row["hash"]
            assert state["revision"] == row["revision"]
            assert state["world_id"] == WORLD
        flags = tuple(name for name in inspect.signature(SQLiteEventStore.append).parameters
                      if name == "bootstrap" or name.endswith("_authorized"))
        columns = {row["name"] for row in old.execute("PRAGMA table_info(commands)")}
        assert set(flags) <= columns, "legacy capability columns differ"
        groups = []
        cursor = 1
        for command in commands:
            selected = [e for e in events if e["command_id"] == command["command_id"]]
            assert selected and command["first_revision"] == cursor
            assert [e["seq"] for e in selected] == list(
                range(cursor, command["last_revision"] + 1)
            )
            typed = [DomainEvent.from_dict(json.loads(e["payload"])) for e in selected]
            assert all(canonical_hash(ev.to_dict()) == raw["hash"]
                       for ev, raw in zip(typed, selected))
            authorizations = {name: bool(command[name]) for name in flags}
            request = {"events": [ev.to_dict() for ev in typed],
                       "expected_revision": cursor - 1}
            request.update(authorizations)
            assert canonical_hash(request) == command["request_hash"], (
                "legacy command provenance hash mismatch"
            )
            groups.append((command["command_id"], cursor - 1, typed,
                           authorizations, command["request_hash"]))
            cursor += len(typed)
        assert cursor - 1 == world["revision"]
        return groups, [(e["seq"], e["command_id"], e["hash"]) for e in events], {
            "revision": world["revision"], "sim_time": world["sim_time"]
        }


def rebuild(source: Path, destination: Path, historical: dict) -> int:
    """Exclusive publish of isolated disposable target after full semantic replay."""
    if os.path.lexists(destination):
        raise FileExistsError("existing target")
    groups, receipts, old_head = read_historical(source)
    stage = Path(tempfile.mkdtemp(prefix=".mig05b-stage-", dir=destination.parent))
    staging = stage / "unpublished.sqlite"
    try:
        with SQLiteEventStore(staging) as store:
            store.create_world(WORLD)
            clock = TimeEngine(store)
            clock.open_session(WORLD)
            try:
                state = store.load(WORLD)
                for command_id, expected_revision, batch, flags, request_hash in groups:
                    assert state.revision == expected_revision
                    state = store.append(WORLD, command_id, state.revision, batch, **flags)
                    actual_hash = store.db.execute(
                        "SELECT request_hash FROM commands WHERE world_id=? AND command_id=?",
                        (WORLD, command_id),
                    ).fetchone()[0]
                    assert actual_hash == request_hash
                assert state.revision == old_head["revision"] and state.time == old_head["sim_time"]
                assert state.to_dict() == historical
                assert store.snapshot(WORLD).to_dict() == state.to_dict()
                assert store.verify(WORLD).to_dict() == state.to_dict()
                current_receipts = store.db.execute(
                    "SELECT seq,command_id,hash FROM events WHERE world_id=? ORDER BY seq",
                    (WORLD,),
                ).fetchall()
                assert current_receipts == receipts
                assert store.db.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
                assert store.db.execute("PRAGMA foreign_key_check").fetchall() == []
            finally:
                clock.close_session(WORLD)
        os.link(staging, destination)  # same filesystem; EEXIST refuses overwrite
        with SQLiteEventStore(destination) as reopened:
            assert reopened.verify(WORLD).to_dict() == historical
        return len(groups)
    finally:
        shutil.rmtree(stage, ignore_errors=True)


def backup_and_continue(target: Path, expected: dict, root: Path) -> None:
    bundle = root / "courier-backup"
    restored = root / "courier-restored.sqlite"
    with SQLiteEventStore(target) as source:
        manifest = create_backup_bundle(source, WORLD, bundle, code_commit=TARGET_SHA)
    assert verify_backup_bundle(bundle) == manifest
    assert len(manifest["worlds"]) == 1 and manifest["schema"] == 42
    assert restore_backup_bundle(bundle, restored) == manifest
    with SQLiteEventStore(restored) as active:
        before = active.verify(WORLD)
        assert before.to_dict() == expected
        clock = TimeEngine(active)
        clock.open_session(WORLD)
        try:
            follow = clock.advance(
                WORLD, seconds=1, command_id="mig05b:courier:continuation",
                expected_revision=before.revision,
            ).state
            assert follow.time == before.time + 1
            assert follow.revision > before.revision
            reject(DuplicateCommand, lambda: clock.advance(
                WORLD, seconds=1, command_id="mig05b:courier:continuation",
                expected_revision=follow.revision,
            ), "duplicate_courier_clock")
            assert active.verify(WORLD).to_dict() == follow.to_dict()
        finally:
            clock.close_session(WORLD)
    with SQLiteEventStore(restored) as second_open:
        assert second_open.verify(WORLD).to_dict() == follow.to_dict()
    with SQLiteEventStore(target) as unchanged:
        assert unchanged.verify(WORLD).to_dict() == expected
    reject(FileExistsError, lambda: restore_backup_bundle(bundle, restored),
           "restore_without_overwrite")


def main() -> None:
    assert SOURCE.exists()
    historical = json.loads(Path("courier-expected-original.json").read_text())
    assert historical["world_id"] == WORLD
    historical.update(schema_version=42, rules_version=57)
    source_digest = digest(SOURCE)
    with tempfile.TemporaryDirectory(prefix="mig05b-courier-") as dirname:
        root = Path(dirname)
        old_copy = root / "old-refusal.sqlite"
        shutil.copy2(SOURCE, old_copy)
        old_copy_digest = digest(old_copy)
        with SQLiteEventStore(old_copy) as old_reader:
            reject(UnsupportedVersion, lambda: old_reader.load(WORLD),
                   "target_refuses_original_schema_rules")
        assert digest(old_copy) == old_copy_digest
        target = root / "isolated42-57.sqlite"
        commands = rebuild(SOURCE, target, historical)
        assert commands == 2
        original_target_sha = digest(target)
        reject(FileExistsError, lambda: rebuild(SOURCE, target, historical),
               "exclusive_destination")
        assert digest(target) == original_target_sha
        backup_and_continue(target, historical, root)
        assert digest(target) == original_target_sha
    assert digest(SOURCE) == source_digest
    print("MIG05B_COURIER_MATRIX " + json.dumps({
        "source": [41, 56], "target": [42, 57],
        "worlds": 1, "historical_events": 97, "historical_commands": 2,
        "real_courier_supply_travel_provenance": True,
        "all_receipts_and_command_hashes_preserved": True,
        "full_replay_and_restore_verified": True,
        "clock_continuation_verified": True,
        "duplicate_command_rejected": True,
        "target_no_overwrite": True, "old_source_immutable": True,
        "test_only": True, "production_migration_approved": False,
        "arbitrary_legacy_worlds_supported": False,
    }, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
